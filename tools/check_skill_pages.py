"""The two SKILL.md pages are held equal to a regeneration from their records.

Written on 2026-11-11 (12:15Z run) as the second check of the class found that
morning (predictions/POST_MORTEMS.md, "A Brier figure rounded twice"): a page
that prints figures from a record, with nothing reading the page back.
`predictions/SKILL.md` and `pm-view/SKILL.md` are written by
`baseline.py --summary` and `score.py --summary`; until this date the committed
page was held current only by the runs' habit of regenerating it with `--dry-run`
and comparing by eye.  A score written without the page regenerated, or a digit
edited on the page, would have passed every check.

What it does, for each page: reads the page's own "Generated by `<generator>` on
<YYYY-MM-DD>" line (exactly one; the generator named is the page's writer; the
date parses, is not after today and not before the newest row of the records
the page summarises), then runs the writer's page function in a fresh
interpreter from the page's folder at that date (the two folders each have a
`score` module, so one process cannot import both) and holds the committed
bytes equal to the regeneration.  A difference is named by line, page beside
regeneration, with the command that rewrites the page.  Exit 1 on any
violation; a record the writer's gates refuse is a violation too (fix the
record, then regenerate), never a pass.

The date itself is held only to its bounds: a page regenerated on a later day
from the same records differs from the committed one in that date alone and
is as true; the tool says so when the date is the only difference.

Usage: python tools/check_skill_pages.py [--today YYYY-MM-DD] [--selftest]
"""

from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
from collections.abc import Callable
from dataclasses import dataclass
from datetime import UTC, date, datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

GENERATED_LINE = re.compile(r"^Generated by `(?P<generator>[^`]+)` on (?P<date>\S+) from ")
_SHOWN = 110  # characters of a line shown in a sentence


@dataclass(frozen=True)
class Page:
    path: str            # repo-relative page
    folder: str          # the folder the regeneration runs from (its modules on sys.path[0])
    generator: str       # the text the page's own line names
    code: str            # python -c code: argv[1] is the date; prints JSON {"text": ..., "newest": ...}


_PREDICTIONS_CODE = """
import json, sys
import pandas as pd
import baseline, score
print(json.dumps({"text": baseline.page_text(pd.Timestamp(sys.argv[1]), score.LEDGER, baseline.BASELINES,
                                             score.OUTCOMES),
                  "newest": baseline.records_newest_day(score.LEDGER, baseline.BASELINES, score.OUTCOMES)}))
"""

_PM_VIEW_CODE = """
import json, sys
from datetime import date
import score
here = score.HERE
manifest = here / "data" / "manifest.json"
entries = json.loads(manifest.read_text(encoding="utf-8")) if manifest.exists() else []
print(json.dumps({"text": score.summary_text(here / "ledger.csv", here / "outcomes.csv",
                                             date.fromisoformat(sys.argv[1]), entries),
                  "newest": score.records_newest_day(here / "ledger.csv", here / "outcomes.csv",
                                                     here / "readings.csv", here / "readings_outcomes.csv")}))
"""

PAGES = (
    Page("predictions/SKILL.md", "predictions", "predictions/baseline.py --summary", _PREDICTIONS_CODE),
    Page("pm-view/SKILL.md", "pm-view", "pm-view/score.py --summary", _PM_VIEW_CODE),
)


# --- the gate (pure) -----------------------------------------------------------------------

def generated_on(text: str, generator: str) -> tuple[str | None, list[str]]:
    """The YYYY-MM-DD the page says it was generated on, and the sentences that refuse the line.
    The date is returned only when it parses; the bounds are judged by `page_violations`."""
    lines = [ln for ln in text.splitlines() if ln.startswith("Generated by `")]
    if not lines:
        return None, [f"carries no 'Generated by `{generator}` on <YYYY-MM-DD>' line"]
    if len(lines) > 1:
        return None, [f"carries {len(lines)} 'Generated by' lines where one is expected"]
    m = GENERATED_LINE.match(lines[0])
    if m is None:
        return None, [f"the 'Generated by' line does not read 'Generated by `{generator}` on <date> from ...': "
                      f"'{lines[0][:_SHOWN]}'"]
    if m["generator"] != generator:
        return None, [f"names its generator as `{m['generator']}`; the page is written by `{generator}`"]
    try:
        day = date.fromisoformat(m["date"])
    except ValueError:
        return None, [f"generated-on date '{m['date']}' is not YYYY-MM-DD"]
    return day.isoformat(), []


def page_violations(text: str, generator: str, regenerate: Callable[[str], str],
                    newest_day: str | None, today: str) -> list[str]:
    """One sentence per violation; [] when the page is the regeneration at its own date and that
    date lies between the newest record row and today.  `regenerate(day)` returns the page as the
    writer would write it on `day`; it may raise ValueError (a record the gates refuse)."""
    day, problems = generated_on(text, generator)
    if day is None:
        return problems
    if day > today:
        return [f"generated on {day}, after today {today}"]
    if newest_day is not None and day < newest_day:
        return [f"generated on {day}, before the newest record row {newest_day}: regenerate with `{generator}`"]
    try:
        regen = regenerate(day)
    except ValueError as exc:
        return [f"the records refuse a regeneration: {str(exc)[:_SHOWN * 3]}; fix the record, then regenerate"]
    if regen == text:
        return []
    page_lines, regen_lines = text.split("\n"), regen.split("\n")
    n = max(len(page_lines), len(regen_lines))
    differing = [i for i in range(n)
                 if (page_lines[i] if i < len(page_lines) else None) != (regen_lines[i] if i < len(regen_lines) else None)]
    first = differing[0]
    shown_page = page_lines[first][:_SHOWN] if first < len(page_lines) else "<no line>"
    shown_regen = regen_lines[first][:_SHOWN] if first < len(regen_lines) else "<no line>"
    return [f"differs from its regeneration at {day} on {len(differing)} of {n} lines; first at line {first + 1}: "
            f"the page prints '{shown_page}', the regeneration prints '{shown_regen}'; "
            f"rewrite the page with `{generator}`, never edit it"]


# --- the live pages ------------------------------------------------------------------------

def regenerated(page: Page, day: str) -> tuple[str, str | None]:
    """(text, newest record day) from the writer's own functions in a fresh interpreter run from the
    page's folder.  ValueError when the writer refuses (its gates, or any failure of the run)."""
    proc = subprocess.run([sys.executable, "-c", page.code, day], cwd=ROOT / page.folder,
                          capture_output=True, text=True)
    if proc.returncode != 0:
        tail = proc.stderr.strip().splitlines()[-1] if proc.stderr.strip() else f"exit {proc.returncode}"
        raise ValueError(tail)
    out = json.loads(proc.stdout)
    return out["text"], out["newest"]


def check_page(page: Page, today: str) -> tuple[list[str], str | None]:
    text = (ROOT / page.path).read_text(encoding="utf-8")
    day, problems = generated_on(text, page.generator)
    if day is None:
        return problems, None
    cache: dict[str, tuple[str, str | None]] = {}

    def regen(d: str) -> str:
        cache[d] = regenerated(page, d)
        return cache[d][0]

    try:
        _, newest = regenerated(page, day)
    except ValueError as exc:
        return [f"the records refuse a regeneration: {str(exc)[:_SHOWN * 3]}; fix the record, then regenerate"], day
    return page_violations(text, page.generator, regen, newest, today), day


# --- self-test -----------------------------------------------------------------------------

_TEMPLATE = ("# A page\n\nGenerated by `x/gen.py --summary` on {day} from `a.csv`. Prose.\n\n"
             "| id | p |\n|---|---|\n| A | 0.2133 |\n| B | 0.6580 |\n\nBrier 0.0455.\n")


def selftest() -> int:
    gen = "x/gen.py --summary"
    clean = _TEMPLATE.format(day="2026-11-06")

    def fake(day: str) -> str:
        return _TEMPLATE.format(day=day)

    cases: list[tuple[str, str, str | None, list[str]]] = [
        # name, page text, newest record day, substrings expected once each among the violations
        ("the regeneration at its own date", clean, "2026-11-06", []),
        ("no record row yet", clean, None, []),
        ("generated on the day of the newest row", clean, "2026-11-06", []),
        ("a digit edited", clean.replace("0.0455", "0.0456"), "2026-11-06",
         ["1 of 11 lines; first at line 10", "page prints 'Brier 0.0456.'", "regeneration prints 'Brier 0.0455.'"]),
        ("a row removed", clean.replace("| B | 0.6580 |\n", ""), "2026-11-06", ["first at line 8"]),
        ("a trailing newline added", clean + "\n", "2026-11-06", ["1 of 12 lines; first at line 12"]),
        ("a trailing space", clean.replace("Prose.", "Prose. "), "2026-11-06", ["first at line 3"]),
        ("another valid date, same records", _TEMPLATE.format(day="2026-11-10"), "2026-11-06", []),
        ("a date in the future", _TEMPLATE.format(day="2026-11-12"), "2026-11-06", ["after today 2026-11-11"]),
        ("a date before the newest row", clean, "2026-11-09", ["before the newest record row 2026-11-09"]),
        ("a date in another format", clean.replace("2026-11-06", "06/11/2026"), None, ["not YYYY-MM-DD"]),
        ("no generated line", clean.replace("Generated by", "Written by"), None, ["carries no 'Generated by"]),
        ("two generated lines", clean.replace("Prose.", "Prose.\nGenerated by `x/gen.py --summary` on 2026-11-06 from z"),
         None, ["carries 2 'Generated by' lines"]),
        ("another generator named", clean.replace("x/gen.py", "y/gen.py"), None, ["names its generator as `y/gen.py"]),
    ]
    failed = 0
    for name, text, newest, expected in cases:
        got = page_violations(text, gen, fake, newest, "2026-11-11")
        joined = " || ".join(got)
        # the gate names one violation at a time; every expected substring is in it
        ok = bool(got) == bool(expected) and len(got) <= 1 and all(e in joined for e in expected)
        if not ok:
            failed += 1
            print(f"selftest FAIL: {name}: expected {expected}, got {got}")

    def refusing(_day: str) -> str:
        raise ValueError("outcomes.csv refused, fix the record: row 2: y of 2")

    got = page_violations(clean, gen, refusing, "2026-11-06", "2026-11-11")
    if not (len(got) == 1 and "refuse a regeneration" in got[0] and "y of 2" in got[0]):
        failed += 1
        print(f"selftest FAIL: a refused record: got {got}")
    total = len(cases) + 1
    if failed:
        print(f"selftest: FAIL ({failed} of {total} cases)")
        return 1
    print(f"selftest: pass ({total} cases)")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--today", help="YYYY-MM-DD (default: the clock, UTC)")
    parser.add_argument("--selftest", action="store_true")
    args = parser.parse_args()
    if args.selftest:
        return selftest()
    today = args.today or datetime.now(UTC).date().isoformat()
    rc = 0
    held: list[str] = []
    for page in PAGES:
        violations, day = check_page(page, today)
        if violations:
            rc = 1
            print(f"skill page: FAIL ({page.path}; fix the page by regenerating it, never the record)")
            for sentence in violations:
                print(f"  {sentence}")
        else:
            held.append(f"{page.path} generated {day}")
    if rc == 0:
        print(f"skill pages: ok ({'; '.join(held)}; each equal to its regeneration at its own date)")
    return rc


if __name__ == "__main__":
    raise SystemExit(main())
