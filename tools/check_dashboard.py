"""Check that the committed paper dashboard is current with the committed paper-log files.

The dashboard (``dashboard/``) is regenerated by ``make dashboard`` after
each forward record; on 2026-10-28 it was found a day stale because two runs
had logged release checks without regenerating it.  This check makes that
visible in ``make lint`` and CI instead of on a reader's screen.

Rule (fixed before the first run on the repository):

1. Regenerate the dashboard into a temporary folder with
   ``qune_research.paperlog.build`` and the same SPECS as
   ``tools/make_paper_dashboard.py``, passing the committed manifest's own
   ``generated_at_utc`` and ``commit`` so that those two lines cannot differ.
2. Pass only if (a) the regenerated ``README.md`` is byte-identical to the
   committed one, (b) the regenerated ``manifest.json`` equals the committed
   one in every field except the chart hashes, (c) the regenerated chart file
   names equal the committed manifest's ``outputs_sha256`` keys, and (d) every
   committed chart file's SHA-256 equals the committed manifest's entry.
   Chart bytes are not compared across machines (fonts may differ between a
   desktop and CI); a chart is a function of the inputs, whose hashes (b)
   compares, and (d) ties the committed images to the committed manifest.
3. Exit 1 on any failure, printing which part failed; "regenerate with
   ``make dashboard`` and commit" is the remedy, never a hand edit.

Fetches nothing and writes nothing inside the repository.

Usage: python tools/check_dashboard.py
"""

from __future__ import annotations

import importlib.util
import json
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from qune_research import paperlog  # noqa: E402

DASH = ROOT / "dashboard"


def _specs() -> list:
    spec = importlib.util.spec_from_file_location("make_paper_dashboard", ROOT / "tools" / "make_paper_dashboard.py")
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module.SPECS


def check() -> list[str]:
    failures: list[str] = []
    committed = json.loads((DASH / "manifest.json").read_text(encoding="utf-8"))
    with tempfile.TemporaryDirectory() as tmp:
        out = Path(tmp)
        fresh = paperlog.build(ROOT, _specs(), out, committed["generated_at_utc"], committed["commit"])
        if (out / "README.md").read_bytes() != (DASH / "README.md").read_bytes():
            failures.append("(a) dashboard/README.md differs from a regeneration from the committed paper-log files")
    for key in sorted(set(committed) | set(fresh)):
        if key != "outputs_sha256" and committed.get(key) != fresh.get(key):
            if key == "studies":
                old = {s["study"]: s for s in committed.get("studies", [])}
                for s in fresh.get("studies", []):
                    if old.get(s["study"]) != s:
                        failures.append(f"(b) manifest.json: {s['study']} differs (records, lines, due date or input hashes)")
                for name in sorted(set(old) - {s["study"] for s in fresh.get("studies", [])}):
                    failures.append(f"(b) manifest.json: {name} no longer generated")
            else:
                failures.append(f"(b) manifest.json field '{key}' differs")
    if set(committed.get("outputs_sha256", {})) != set(fresh.get("outputs_sha256", {})):
        failures.append("(c) chart file names differ: committed "
                        f"{sorted(committed.get('outputs_sha256', {}))}, regenerated {sorted(fresh.get('outputs_sha256', {}))}")
    for name, digest in sorted(committed.get("outputs_sha256", {}).items()):
        path = DASH / name
        if not path.exists() or paperlog.sha256(path) != digest:
            failures.append(f"(d) dashboard/{name} missing or not the file the manifest names")
    return failures


def main() -> int:
    failures = check()
    committed = json.loads((DASH / "manifest.json").read_text(encoding="utf-8"))
    print(f"dashboard generated {committed['generated_at_utc']} from commit {committed['commit']}; "
          f"{len(committed['studies'])} studies, {len(committed.get('outputs_sha256', {}))} chart files")
    for line in failures:
        print("FAIL " + line)
    if failures:
        print("stale: regenerate with `make dashboard` and commit; never edit dashboard/ by hand")
        return 1
    print("current: README.md and manifest.json match a regeneration from the committed paper-log files")
    return 0


if __name__ == "__main__":
    sys.exit(main())
