"""pm-view/SKILL.md is a regeneration from its records (tools/check_skill_pages.py,
2026-11-11 12:15Z; the class of predictions/POST_MORTEMS.md "A Brier figure rounded
twice": a page printing figures from a record with nothing reading the page back).
These tests hold the committed page equal to `score.summary_text` at the page's own
date, `write_summary` writing exactly that text, the date between the newest record
row and today, and the gate naming an alteration by line.

Until 2026-11-13 06:15Z the page's date and its counts were typed into these tests
("2026-11-06", "| fomc_bills | 3 | 0 |", "Readings on record: 4;"), so the first weekly
regeneration of the page failed four of them for no defect in the page: the same class
as a figure typed onto a page from a record (BUILD_LOG 2026-11-13 06:15Z). The tests now
read the page's own date from its "Generated by" line and build each alteration from the
page as it stands, naming the altered line by where it is."""
import csv
import json
import re
import sys
from datetime import UTC, date, datetime
from pathlib import Path

import pytest
import score as S

PM_VIEW = Path(__file__).resolve().parents[1]
ROOT = PM_VIEW.parent
sys.path.insert(0, str(ROOT / "tools"))

import check_skill_pages as csp  # noqa: E402

PAGE = PM_VIEW / "SKILL.md"
LEDGER, OUTCOMES = PM_VIEW / "ledger.csv", PM_VIEW / "outcomes.csv"
READINGS, READINGS_OUTCOMES = PM_VIEW / "readings.csv", PM_VIEW / "readings_outcomes.csv"


def entries() -> list[dict]:
    manifest = PM_VIEW / "data" / "manifest.json"
    return json.loads(manifest.read_text(encoding="utf-8")) if manifest.exists() else []


def regenerate(day: str) -> str:
    return S.summary_text(LEDGER, OUTCOMES, date.fromisoformat(day), entries())


def page_day() -> str:
    """The date the committed page's own "Generated by" line names; the tests regenerate at it."""
    day, problems = csp.generated_on(PAGE.read_text(encoding="utf-8"), S.PAGE_GENERATOR)
    assert problems == [] and day is not None
    return day


def test_the_committed_page_is_the_regeneration_at_its_own_date():
    text = PAGE.read_text(encoding="utf-8")
    assert regenerate(page_day()) == text


def test_the_page_date_lies_between_the_newest_record_row_and_today():
    text = PAGE.read_text(encoding="utf-8")
    day = page_day()
    newest = S.records_newest_day(LEDGER, OUTCOMES, READINGS, READINGS_OUTCOMES)
    today = datetime.now(UTC).date().isoformat()
    assert newest is not None
    assert newest <= day <= today
    assert csp.page_violations(text, S.PAGE_GENERATOR, regenerate, newest, today) == []


def _main_paths(skill: Path) -> list[str]:
    return ["--today", page_day(), "--ledger", str(LEDGER), "--outcomes", str(OUTCOMES), "--skill", str(skill),
            "--manifest", str(PM_VIEW / "data" / "manifest.json")]


def test_summary_dry_run_prints_exactly_the_page_and_writes_nothing(tmp_path, capsys):
    # 2026-11-12 06:15Z (predictions/POST_MORTEMS.md "A dry run that wrote the page"): `--summary --dry-run`
    # wrote SKILL.md dated that day, because main read the flag on its scoring branch only; a page so
    # written is a true regeneration, so the page check admits it. The tool must not write it.
    skill = tmp_path / "SKILL.md"
    assert S.main(["--summary", "--dry-run", *_main_paths(skill)]) == 0
    assert capsys.readouterr().out == regenerate(page_day()) == PAGE.read_text(encoding="utf-8")
    assert sorted(p.name for p in tmp_path.iterdir()) == []


def test_summary_without_dry_run_writes_the_page_and_says_so(tmp_path, capsys):
    skill = tmp_path / "SKILL.md"
    assert S.main(["--summary", *_main_paths(skill)]) == 0
    assert capsys.readouterr().out == "wrote SKILL.md\n"
    assert skill.read_text(encoding="utf-8") == regenerate(page_day())


def test_scoring_dry_run_writes_nothing_either(tmp_path):
    # the other path of main, with a reading on record and nothing due, no manifest and so no fetch
    rd = tmp_path / "readings.csv"
    rd.write_text(READINGS.read_text(encoding="utf-8"), encoding="utf-8")
    before = {p.name: p.read_bytes() for p in tmp_path.iterdir()}
    assert S.main(["--dry-run", "--today", "2026-11-01", "--ledger", str(LEDGER), "--outcomes", str(tmp_path / "o.csv"),
                   "--readings", str(rd), "--readings-outcomes", str(tmp_path / "ro.csv"),
                   "--manifest", str(tmp_path / "none.json")]) == 0
    assert {p.name: p.read_bytes() for p in tmp_path.iterdir()} == before


def test_write_summary_writes_exactly_summary_text(tmp_path):
    out = tmp_path / "SKILL.md"
    S.write_summary(LEDGER, OUTCOMES, out, date.fromisoformat(page_day()), entries())
    assert out.read_text(encoding="utf-8") == regenerate(page_day()) == PAGE.read_text(encoding="utf-8")


def _bump(pattern: str):
    """Add one to the first integer the pattern captures on the first line it matches;
    returns the altered text and that line's 1-based number."""
    def alter(text: str) -> tuple[str, int]:
        lines = text.split("\n")
        for i, line in enumerate(lines):
            m = re.search(pattern, line)
            if m:
                lines[i] = line[:m.start(1)] + str(int(m.group(1)) + 1) + line[m.end(1):]
                return "\n".join(lines), i + 1
        raise AssertionError(f"no line matches {pattern!r}")
    alter.__name__ = f"bump:{pattern}"
    return alter


def _drop_first_table_row(text: str) -> tuple[str, int]:
    """Remove the first body row of the first table; the first differing line is that row's."""
    lines = text.split("\n")
    for i, line in enumerate(lines):
        if line.startswith("|---"):
            del lines[i + 1]
            return "\n".join(lines), i + 2
    raise AssertionError("no table on the page")


ALTERATIONS = [
    _bump(r"^\| fomc_bills \| (\d+) \|"),      # a count typed onto the page
    _bump(r"^Scored calls: (\d+)\."),          # the headline count
    _bump(r"^Readings on record: (\d+);"),     # the readings count
    _drop_first_table_row,                      # a row removed
]


@pytest.mark.parametrize("alteration", ALTERATIONS, ids=lambda f: f.__name__)
def test_an_alteration_of_the_committed_page_is_named_by_line(alteration):
    text = PAGE.read_text(encoding="utf-8")
    altered, line = alteration(text)
    assert altered != text
    # the today bound is far off on purpose: this test is about the line named, not the date
    (only,) = csp.page_violations(altered, S.PAGE_GENERATOR, regenerate, None, "2099-12-31")
    assert f"first at line {line}" in only and "rewrite the page with `pm-view/score.py --summary`" in only


def test_the_alterations_apply_to_the_page_in_the_records_next_state(tmp_path):
    # 2026-11-13 18:15Z, the class search after the 06:15Z failure: the record's next state is a scored
    # call, which the committed ledger has never held.  A synthetic call scored by score.py itself on a
    # synthetic resolved market, beside a copy of the committed readings records, regenerated at a later
    # day; every alteration builder must still find its line there, so the expectations are shown to come
    # from the page and not from its state on the day the test was written.  Temporary files only.
    call = {"id": "P1-2026-11-03", "made_on": "2026-11-03", "venue": "polymarket", "market_id": "3215008",
            "condition_id": "0xcond", "yes_token_id": "111", "proposition": "Hike of 25 bp on 9 December",
            "settles_on": "resolves YES on a 25 bp hike at the 9 December meeting", "due_on": "2026-12-09",
            "market_mid": "0.735", "market_spread": "0.010", "volume_usdc": "500000", "desk_p": "0.60",
            "method": "stated", "method_p": "", "range_lo": "", "range_hi": "", "basis": "bills", "quote_sha256": "a" * 64}
    gamma = {"id": "3215008", "conditionId": "0xcond", "clobTokenIds": '["111", "222"]', "outcomes": '["Yes", "No"]',
             "umaResolutionStatus": "resolved", "closed": True, "outcomePrices": '["1", "0"]'}
    clob = {"tokens": [{"token_id": "111", "winner": True}, {"token_id": "222", "winner": False}]}

    def fetcher(table):
        def f(url):
            for k, v in table.items():
                if url.endswith(k):
                    return json.dumps(v).encode()
            raise OSError(f"no record for {url}")
        return f

    led, out = tmp_path / "ledger.csv", tmp_path / "outcomes.csv"
    with led.open("w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=list(call))
        w.writeheader()
        w.writerow(call)
    for name in ("readings.csv", "readings_outcomes.csv"):
        (tmp_path / name).write_bytes((PM_VIEW / name).read_bytes())
    assert S.run(led, out, fetcher({"/markets/3215008": gamma}), fetcher({"/markets/0xcond": clob}),
                 date(2026, 12, 10), dry_run=False) == 0

    def regen(day: str) -> str:
        return S.summary_text(led, out, date.fromisoformat(day), [])

    future = regen("2026-12-10")
    assert "Scored calls: 1. Brier, desk:" in future and "| P1-2026-11-03 |" in future
    for alteration in ALTERATIONS:
        altered, line = alteration(future)
        assert altered != future, alteration.__name__
        (only,) = csp.page_violations(altered, S.PAGE_GENERATOR, regen, None, "2099-12-31")
        assert f"first at line {line}" in only, (alteration.__name__, only)


def test_the_newest_record_day_reads_every_record_the_page_summarises(tmp_path):
    # calls, readings and both scored records, through the scored records' gates; a missing file is empty
    led = tmp_path / "ledger.csv"
    led.write_text("id,made_on\nC1,2026-11-03\n", encoding="utf-8")
    rd = tmp_path / "readings.csv"
    rd.write_text("id,made_on\nR1,2026-11-06\n", encoding="utf-8")
    assert S.records_newest_day(led, tmp_path / "outcomes.csv", rd, tmp_path / "readings_outcomes.csv") == "2026-11-06"
    assert S.records_newest_day(tmp_path / "none.csv", tmp_path / "none2.csv", tmp_path / "none3.csv",
                                tmp_path / "none4.csv") is None
